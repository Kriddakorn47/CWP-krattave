# ไฟล์สำหรับรันเทสต์ (ตอน defense เขาจะแก้ไฟล์นี้เพื่อลองบอร์ดอื่น ๆ)

from checkmate import checkmate


def main():
    # บอร์ดต้องเขียนชิดซ้ายสุด ห้ามเยื้อง
    # ไม่เช่นนั้นช่องว่างนำหน้าจะกลายเป็นส่วนของบอร์ด แล้วบอร์ดจะไม่เป็นสี่เหลี่ยมจัตุรัส
    # เครื่องหมาย \ หลัง """ และท้ายบอร์ด ช่วยไม่ให้มีบรรทัดว่างเกินมา
    board = """\
...K
....
....
....\
"""
    checkmate(board)   # ผลลัพธ์ที่คาดหวัง: Success (P กิน K ได้)


# รันฟังก์ชัน main เฉพาะตอนสั่ง python3 main.py โดยตรง
# (ไม่รันถ้าไฟล์นี้ถูก import จากที่อื่น)
if __name__ == "__main__":
    main()